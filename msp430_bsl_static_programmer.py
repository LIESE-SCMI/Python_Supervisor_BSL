def main():
    parser = argparse.ArgumentParser(
        description="MSP430 BSL Programmer — programa via UART backchannel usando archivos TI-TXT"
    )
    parser.add_argument("-p", "--port",
        help="Puerto serie (ej. COM3, /dev/ttyUSB0)")
    parser.add_argument("-f", "--file",
        help="Archivo TI-TXT a cargar (.txt). Si se omite, usa el firmware hardcodeado.")
    parser.add_argument("-b", "--baud", type=int, default=9600,
        help="Baudrate (default: 9600)")
    parser.add_argument("--search-dir", default="./titxt_files",
        help="Directorio donde buscar archivos .txt (default: directorio actual)")
    parser.add_argument("--list-ports", action="store_true",
        help="Lista los puertos serie disponibles y sale")
    args = parser.parse_args()

    # Solo listar puertos
    if args.list_ports:
        ports = list_serial_ports()
        if ports:
            print("Puertos disponibles:")
            for p in ports:
                print(f"  {p}")
        else:
            print("No se encontraron puertos.")
        return

    # Selección de puerto
    port = args.port or select_port_interactive()

    # Selección de archivo (solo si se especifica -f)
    if args.file:
        filepath = args.file
        if not os.path.isfile(filepath):
            print(f"✗ Archivo no encontrado: {filepath}")
            sys.exit(1)
    else:
        filepath = None

    bsl = MSP430_BSL(port=port, baudrate=args.baud)
    
    # Programar: hardcodeado si no se pasa -f, TI-TXT si se pasa
    if args.file:
        success = bsl.program_ti_txt(args.file)
    else:
        print("[INFO] Sin archivo TI-TXT especificado → usando firmware hardcodeado")
        success = bsl.program_hardcoded()

    sys.exit(0 if success else 1)

main()